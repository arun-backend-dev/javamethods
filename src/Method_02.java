

//We cannot create another method inside a method




/*
 Question: How does the JVM know where to search first during a method call — in the object or in the class?

4-line Answer:
The JVM knows where to search based on the bytecode instruction generated by the compiler.
For static methods the compiler generates invokestatic, so JVM searches in the class.
For instance methods it generates invokevirtual, so JVM searches in the object first.
So the compiler decides the search path, and the JVM simply follows the instruction.
 */

public class Method_02 {
 static void m1() {
	 System.out.println("Static m1()");
	 
 }
  void m2() {
	 System.out.println("Static m2()");
	 
 }
  
  
  public static void main(String[] args) {
	  //m1() is static
	  //Static methods can be called without object
	  //JVM calls it directly using class name implicitly


	m1();
	
	//A new object of Method_02 is created in heap memory.
	//Reference variable me1 stores the memory address of that object.
	
	Method_02 me1=new Method_02();
	//**JVM does NOT search in the object.
	//It directly searches in the CLASS.**
	//Because m1() is static, the JVM does not use the object for searching the method.
	/*
	 * 🔍 DEEP EXPLANATION
👉 Step 1: Compiler sees me1.m1()

The compiler looks at the type of me1 → Method_02.

Then it checks inside the class Method_02:

Does Method_02 have m1()?

Yes → m1() is static.

So compiler decides:

✔ "This is a class method call, not an object method call."*/
	me1.m1();
	/*
	 * ✔ JVM searches in the object first
✔ Then in the class (for method definition)

Because instance methods belong to OBJECTS, not classes.*/
	me1.m2();
	
}
}
















